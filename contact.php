                        function handleSubjectChange(value) {
                            const luxuryDiv = document.getElementById('luxury-fields');
                            const serviceInput = document.getElementById('service');
                            
                            // inputs
                            const luxuryInputs = luxuryDiv.querySelectorAll('input');
                            
                            if (value === 'Luxury Car Booking') {
                                luxuryDiv.classList.remove('hidden');
                                luxuryDiv.classList.add('grid');
                                
                                luxuryInputs.forEach(i => i.required = true);
                                if (serviceInput) serviceInput.value = 'luxury-car';
                            } else {
                                luxuryDiv.classList.remove('grid');
                                luxuryDiv.classList.add('hidden');
                                
                                luxuryInputs.forEach(i => { i.required = false; i.value = ''; });
                                if (serviceInput) {
                                    if (value === 'Tourist Hire Booking') {
                                        serviceInput.value = 'tourist-hire';
                                    } else {
                                        serviceInput.value = '';
                                    }
                                }
                            }
                        }

